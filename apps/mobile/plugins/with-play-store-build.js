const { withAndroidManifest, withSettingsGradle } = require("@expo/config-plugins");

const marker = "// Picket Play build (generated by Expo config plugin)";
const playBuild = process.env.PICKET_PLAY_BUILD === "1";

function configureSettingsGradle(source) {
  if (source.includes(marker)) return source;

  const pluginsBlock = `plugins {
  id("com.facebook.react.settings")
  id("expo-autolinking-settings")
}`;
  if (!source.includes(pluginsBlock)) {
    throw new Error("Unable to locate Expo settings plugins block.");
  }

  source = source.replace(
    pluginsBlock,
    `${pluginsBlock}\n\n${marker}\ndef picketPlayBuild = System.getenv("PICKET_PLAY_BUILD") == "1"\nif (picketPlayBuild) {\n  expoAutolinking.exclude = ["picket-app-updates"]\n}`,
  );

  const rnCommand = "ex.autolinkLibrariesFromCommand(expoAutolinking.rnConfigCommand)";
  if (!source.includes(rnCommand)) {
    throw new Error("Unable to locate Expo React Native autolinking command.");
  }
  return source.replace(
    rnCommand,
    `def picketRnConfigCommand = expoAutolinking.rnConfigCommand\n    if (picketPlayBuild) {\n      picketRnConfigCommand = picketRnConfigCommand + ["--exclude", "picket-app-updates"]\n    }\n    ex.autolinkLibrariesFromCommand(picketRnConfigCommand)`,
  );
}

function blockPermission(manifest, permission) {
  const permissions = (manifest["uses-permission"] ??= []);
  const existing = permissions.find(
    (entry) => entry.$?.["android:name"] === permission,
  );
  if (existing) {
    existing.$["tools:node"] = "remove";
    return;
  }
  permissions.push({
    $: { "android:name": permission, "tools:node": "remove" },
  });
}

function configureManifest(manifest, isPlayBuild) {
  if (!isPlayBuild) return manifest;
  manifest.$ ??= {};
  manifest.$["xmlns:tools"] ??= "http://schemas.android.com/tools";
  blockPermission(manifest, "android.permission.REQUEST_INSTALL_PACKAGES");
  blockPermission(manifest, "android.permission.SYSTEM_ALERT_WINDOW");
  return manifest;
}

module.exports = function withPlayStoreBuild(config) {
  config = withSettingsGradle(config, (mod) => {
    if (mod.modResults.language !== "groovy") return mod;
    mod.modResults.contents = configureSettingsGradle(mod.modResults.contents);
    return mod;
  });

  if (!playBuild) return config;
  return withAndroidManifest(config, (mod) => {
    const manifest = mod.modResults.manifest;
    manifest.$ ??= {};
    manifest.$["xmlns:tools"] ??= "http://schemas.android.com/tools";
    blockPermission(manifest, "android.permission.REQUEST_INSTALL_PACKAGES");
    blockPermission(manifest, "android.permission.SYSTEM_ALERT_WINDOW");
    return mod;
  });
};

module.exports.configureSettingsGradle = configureSettingsGradle;
module.exports.configureManifest = configureManifest;
